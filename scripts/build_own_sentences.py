def _format_module_depths() -> str:
    """Format default depths per module dynamically from CAPABILITY_PROFILES table."""
    depth_groups: dict[str, list[str]] = {}
    for intent, profile in CAPABILITY_PROFILES.items():
        if profile.default_depth is not None:
            depth_str = f"{profile.default_depth.min_depth:.0f}–{profile.default_depth.max_depth:.0f} dbar"
        else:
            depth_str = "unspecified (none)"
        depth_groups.setdefault(depth_str, []).append(intent.value)

    parts: list[str] = []
    # Sort with fixed depth ranges first
    for depth_str in sorted(depth_groups.keys()):
        intents_str = ", ".join(depth_groups[depth_str])
        parts.append(f"{depth_str} for {intents_str}")
    return "; ".join(parts)


def load_refusal_categories() -> list[dict]:
    """Load canonical refusal categories and sentences from data/refusal_categories.json."""
    if not REFUSAL_CATEGORIES_PATH.exists():
        raise FileNotFoundError(f"Missing refusal categories file: {REFUSAL_CATEGORIES_PATH}")
    with open(REFUSAL_CATEGORIES_PATH, "r", encoding="utf-8") as f:
        data = json.load(f)
    return data.get("categories", [])


